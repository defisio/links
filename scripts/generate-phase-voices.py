"""Optional asset generation, not required by the site build.

Python 3.12 venv: pip install kokoro==0.9.4 soundfile
Requires espeak-ng and ffmpeg. Generates fixed pt-BR phrases locally with Kokoro.
"""
from pathlib import Path
import base64
import json
import subprocess
import wave

import numpy as np
import torch
from kokoro import KPipeline

PHRASES = {
    "preparation": "Prepare-se.",
    "warmup": "Aquecimento.",
    "exercise": "Exercício.",
    "rest": "Descanso.",
    "setRest": "Pausa entre séries.",
    "cooldown": "Desaquecimento.",
    "complete": "Treino concluído.",
    "test": "Teste de som.",
}
ROOT = Path(__file__).resolve().parents[1]
torch.set_num_threads(4)
pipeline = KPipeline(lang_code="p", repo_id="hexgrad/Kokoro-82M", device="cpu")
encoded = {}
for key, phrase in PHRASES.items():
    chunks = [result.audio.numpy() for result in pipeline(phrase, voice="pf_dora", speed=1.0)]
    if not chunks:
        raise RuntimeError(f"No audio produced for {phrase}")
    audio = np.concatenate(chunks).astype(np.float32)
    peaks = np.flatnonzero(np.abs(audio) > 0.004)
    if not len(peaks):
        raise RuntimeError(f"Silent audio for {phrase}")
    audio = audio[max(0, peaks[0] - 720):min(len(audio), peaks[-1] + 960)]
    audio *= 0.72 / max(0.01, float(np.max(np.abs(audio))))
    result = subprocess.run([
        "ffmpeg", "-v", "error", "-f", "f32le", "-ar", "24000", "-ac", "1", "-i", "pipe:0",
        "-ar", "8000", "-ac", "1", "-f", "u8", "pipe:1",
    ], input=audio.tobytes(), stdout=subprocess.PIPE, check=True)
    pcm = result.stdout
    encoded[key] = base64.b64encode(pcm).decode("ascii")
    if key == "test":
        with wave.open(str(ROOT / "public/timer/voice-test.wav"), "wb") as output:
            output.setnchannels(1)
            output.setsampwidth(1)
            output.setframerate(8000)
            output.writeframes(pcm)
    print(json.dumps({"phase": key, "text": phrase, "seconds": round(len(pcm) / 8000, 3)}), flush=True)

module = '''// Generated by scripts/generate-phase-voices.py. See docs/phase-voice-assets.md.
export const PHASE_VOICE_TEXT = ''' + json.dumps(PHRASES, ensure_ascii=False, indent=2) + ''' as const;
export type PhaseVoiceKey = keyof typeof PHASE_VOICE_TEXT;
const encoded = ''' + json.dumps(encoded, indent=2) + ''';
let cached: Record<PhaseVoiceKey, Uint8Array> | null = null;
export function getPhaseVoices(): Record<PhaseVoiceKey, Uint8Array> {
  cached ??= Object.fromEntries(Object.entries(encoded).map(([key, value]) => [key, Uint8Array.from(atob(value), character => character.charCodeAt(0))])) as Record<PhaseVoiceKey, Uint8Array>;
  return cached;
}
'''
(ROOT / "lib/tabata/phase-voices.ts").write_text(module)
with wave.open(str(ROOT / "public/timer/unlock.wav"), "wb") as output:
    output.setnchannels(1)
    output.setsampwidth(1)
    output.setframerate(8000)
    output.writeframes(bytes([128] * 800))
