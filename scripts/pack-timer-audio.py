"""Package the processed MP3s for the offline media track. Requires ffmpeg.

Does not run during site builds; generated sources/assets are committed.
"""
from pathlib import Path
import base64
import json
import subprocess
import wave

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/tabata-audio"
RATE = 16000
PHRASES = {
    "preparation": "Prepare-se.", "warmup": "Aquecimento.",
    "exercise": "Exercício.", "rest": "Descanso.",
    "setRest": "Pausa entre séries.", "cooldown": "Desaquecimento.",
    "complete": "Treino concluído.", "test": "Teste de som.",
}


def decode(name):
    return subprocess.run([
        "ffmpeg", "-v", "error", "-i", str(ASSETS / f"{name}.mp3"),
        "-ac", "1", "-ar", str(RATE), "-f", "u8", "pipe:1",
    ], capture_output=True, check=True).stdout


def wav(name, pcm):
    with wave.open(str(ROOT / f"public/timer/{name}.wav"), "wb") as output:
        output.setnchannels(1)
        output.setsampwidth(1)
        output.setframerate(RATE)
        output.writeframes(pcm)


def main():
    voices = {key: decode(key) for key in PHRASES}
    effects = {key: decode(name) for key, name in {
        "clock": "clock", "transition": "ready", "complete": "finish",
    }.items()}
    # A single clean tick from the continuous clock for the 3-2-1 accents.
    effects["countdown"] = effects["clock"][:round(.2 * RATE)]
    wav("voice-test", voices["test"])
    wav("unlock", bytes([128]) * (RATE // 10))
    wav("ready", effects["transition"])
    for key in ["transition", "countdown", "complete"]:
        wav(key, effects[key])
    def encoded(clips):
        return {key: base64.b64encode(pcm).decode() for key, pcm in clips.items()}
    module = '''// Generated by scripts/pack-timer-audio.py. See docs/phase-voice-assets.md.
export const PHASE_VOICE_TEXT = ''' + json.dumps(PHRASES, ensure_ascii=False, indent=2) + ''' as const;
export const AUDIO_ASSET_SAMPLE_RATE = 16000;
export type PhaseVoiceKey = keyof typeof PHASE_VOICE_TEXT;
export type WorkoutEffectKey = "clock" | "countdown" | "transition" | "complete";
const encoded = ''' + json.dumps(encoded(voices), indent=2) + ''';
const encodedEffects = ''' + json.dumps(encoded(effects), indent=2) + ''';
function decode<T extends string>(clips: Record<T, string>): Record<T, Uint8Array> {
  return Object.fromEntries(Object.entries<string>(clips).map(([key, value]) => [key, Uint8Array.from(atob(value), character => character.charCodeAt(0))])) as Record<T, Uint8Array>;
}
let voices: Record<PhaseVoiceKey, Uint8Array> | null = null;
let effects: Record<WorkoutEffectKey, Uint8Array> | null = null;
export function getPhaseVoices(): Record<PhaseVoiceKey, Uint8Array> {
  return voices ??= decode(encoded);
}
export function getWorkoutEffects(): Record<WorkoutEffectKey, Uint8Array> {
  return effects ??= decode(encodedEffects);
}
'''
    (ROOT / "lib/tabata/phase-voices.ts").write_text(module)


if __name__ == "__main__":
    main()
